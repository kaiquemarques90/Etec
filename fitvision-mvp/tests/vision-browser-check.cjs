const {chromium}=require(process.env.PLAYWRIGHT_MODULE||'playwright');
const assert=require('node:assert/strict');
(async()=>{
 const browser=await chromium.launch({headless:true,channel:'msedge'});
 const page=await browser.newPage({viewport:{width:1280,height:900}});
 const errors=[],external=[];page.on('pageerror',e=>errors.push(e.message));
 page.on('request',req=>{if(!req.url().startsWith('http://localhost:3000')&&!req.url().startsWith('blob:')&&!req.url().startsWith('data:'))external.push(req.url());});
 await page.goto('http://localhost:3000');
 await page.locator('#pose-analyze').click();
 assert.match(await page.locator('#analysis-status').innerText(),/Escolha ou capture/);
 await page.locator('#photo').setInputFiles('tests/fixtures/pose.jpg');
 await page.waitForFunction(()=>document.querySelector('#profile-status').textContent.includes('Foto carregada'));
 await page.locator('#pose-analyze').click();
 await page.waitForFunction(()=>!document.querySelector('#pose-analyze').disabled,{},{timeout:60000});
 const status=await page.locator('#analysis-status').innerText();
 assert.match(status,/Pose detectada|Endireite|Ombros, quadril/);
 assert.equal(await page.locator('#pose-canvas').isVisible(),true);
 assert.equal(await page.locator('#calibration').isVisible(),true);
 assert.match(await page.locator('#preview-status').innerText(),/Alinhamento automático/);
 await page.locator('#estimate-shoulders').click();
 assert.match(await page.locator('#estimate-result').innerText(),/Medidas projetadas estimadas/);
 await page.locator('#review-estimates').click();
 assert.equal(await page.locator('[name=shoulders]').inputValue() !== '',true);
 assert.equal(await page.locator('[name=shoulders]').locator('..').locator('[data-origin]').innerText(),'Medida projetada estimada · revise');
 await page.locator('#profile-form [type=submit]').click();
 assert.equal(await page.locator('[name=shoulders]').locator('..').locator('[data-origin]').innerText(),'Medida projetada estimada · revise');
 await page.locator('[name=shoulders]').fill('40');
 assert.equal(await page.locator('[name=shoulders]').locator('..').locator('[data-origin]').innerText(),'');
 await page.locator('#clear-photo').click();
 assert.equal(await page.locator('#pose-canvas').isVisible(),false);
 // Camera failure has a usable fallback; no permission is granted here.
 await page.context().clearPermissions();
 await page.locator('#camera-start').click();
 await page.waitForFunction(()=>document.querySelector('#analysis-status').textContent.includes('Não foi possível'),{},{timeout:15000});
 assert.equal(await page.locator('#camera-start').isEnabled(),true);
 await page.setViewportSize({width:390,height:844});
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
 assert.deepEqual(errors,[]);assert.deepEqual(external,[]);
 await browser.close();console.log('Real local MediaPipe inference passed; no external requests; photo reset, camera fallback and mobile layout passed.');
})().catch(error=>{console.error(error);process.exit(1);});
